"""Collect notices from the actual locked crates and installed runtime packages."""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[1]


def command(args, **kwargs):
    return subprocess.check_output(args, text=True, **kwargs).strip()


def rust_tool(name):
    return shutil.which(name) or str(Path.home() / '.cargo/bin' / name)


def rust_notices():
    metadata = json.loads(command([rust_tool('cargo'), 'metadata', '--locked',
                                   '--offline', '--format-version', '1'], cwd=ROOT))
    parts = ['Rust dependency notices for Kanata Studio Rust',
             'Generated by tools/license_materials.py; includes build dependencies.',
             'Cargo.lock SHA-256: ' + hashlib.sha256((ROOT / 'Cargo.lock').read_bytes()).hexdigest()]
    for package in sorted(metadata['packages'], key=lambda p: (p['name'], p['version'])):
        if package['id'] in metadata['workspace_members']:
            continue
        directory = Path(package['manifest_path']).parent
        files = sorted(p for p in directory.iterdir() if p.is_file()
                       and p.name.lower().startswith(('license', 'copying', 'notice')))
        if package.get('license_file'):
            files = sorted(set(files + [directory / package['license_file']]))
        if not files or not package.get('license'):
            raise RuntimeError(f"Review license manually: {package['name']}")
        # A new dependency or changed expression requires an explicit review.
        if package['license'] not in {'MIT', 'MIT OR Apache-2.0', 'Unlicense OR MIT',
                                      '(MIT OR Apache-2.0) AND Unicode-3.0'}:
            raise RuntimeError(f"Unreviewed Rust license: {package['name']}: {package['license']}")
        parts += [f"\n{'=' * 72}\n{package['name']} {package['version']}",
                  'License: ' + package['license'],
                  'Upstream: ' + (package.get('repository') or package.get('homepage') or ''),
                  f"Source: https://crates.io/crates/{package['name']}/{package['version']}"]
        for path in files:
            parts += ['\n--- ' + path.name + ' ---\n', path.read_text().rstrip()]
    return '\n'.join(parts) + '\n'


def check_rust_notices():
    expected = rust_notices()
    path = ROOT / 'licenses/RUST-DEPENDENCIES.txt'
    if not path.is_file() or path.read_text() != expected:
        raise RuntimeError('Rust notices are stale. Run python3 tools/license_materials.py --write')


def copy_project_notices(target):
    check_rust_notices()
    for name in ('LICENSE', 'THIRD_PARTY_NOTICES.md', 'LICENSING.md'):
        shutil.copy2(ROOT / name, target / name)
    shutil.copytree(ROOT / 'licenses', target / 'licenses', dirs_exist_ok=True)
    sysroot = Path(command([rust_tool('rustc'), '--print', 'sysroot']))
    docs = sysroot / 'share/doc/rust'
    # COPYRIGHT.html also covers older toolchains without COPYRIGHT-library.html.
    if not (docs / 'COPYRIGHT.html').is_file() or not (docs / 'licenses').is_dir():
        raise RuntimeError('Rust toolchain copyright notices missing: ' + str(docs))
    rust = target / 'licenses/rust-toolchain'
    rust.mkdir(parents=True, exist_ok=True)
    for path in docs.glob('COPYRIGHT*.html'):
        shutil.copy2(path, rust / path.name)
    shutil.copytree(docs / 'licenses', rust / 'licenses', dirs_exist_ok=True)
    (rust / 'VERSION.txt').write_text(command([rust_tool('rustc'), '-Vv']) + '\n')


def debian_owners(paths):
    """Resolve exact paths, including merged-/usr aliases; never guess by basename."""
    aliases = {}
    for path in paths:
        for value in {str(path), str(path.resolve())}:
            aliases[value] = path
            if value.startswith(('/usr/lib/', '/usr/bin/')):
                aliases[value[4:]] = path
    result = subprocess.run(['dpkg-query', '-S', *sorted(aliases)], text=True,
                            capture_output=True)
    owners = {}
    for line in result.stdout.splitlines():
        if ': ' not in line:
            continue
        package, filename = line.rsplit(': ', 1)
        if filename in aliases:
            if ', ' in package or package.startswith('diversion '):
                raise RuntimeError('Ambiguous package owner: ' + line)
            owners.setdefault(aliases[filename], set()).add(package)
    missing = [str(path) for path in paths if len(owners.get(path, ())) != 1]
    if missing:
        raise RuntimeError('Missing or ambiguous package owners: ' + ', '.join(missing))
    return {path: next(iter(packages)) for path, packages in owners.items()}


def collect_native_sources(bundle, origins):
    """Put exact Debian source packages inside the bundle, with notices and inventory."""
    if not shutil.which('dpkg-query'):
        raise RuntimeError('Redistributable bundles require Debian and enabled deb-src repositories. '
                           'Use --development only for a private local bundle; see LICENSING.md.')
    owners = debian_owners(set(origins.values()))
    packages = {}
    sources = bundle / 'sources/debian'
    sources.mkdir(parents=True)
    for package in sorted(set(owners.values())):
        details = command(['dpkg-query', '-W',
                           '-f=${Package}\t${Version}\t${source:Package}\t${source:Version}', package]).split('\t')
        name, version, source, source_version = details
        if name.startswith(('libqt6', 'qml6-', 'qt6-')) and source not in {
                'qt6-base', 'qt6-declarative', 'qt6-wayland', 'qt6-svg', 'qt6-imageformats'}:
            raise RuntimeError('Unreviewed Qt module: ' + name)
        notice = Path('/usr/share/doc') / name / 'copyright'
        if not notice.is_file():
            raise RuntimeError('Missing distribution copyright file: ' + str(notice))
        destination = bundle / 'licenses/native' / package
        destination.mkdir(parents=True)
        shutil.copy2(notice, destination / 'copyright')
        packages[package] = dict(name=name, version=version, source=source,
                                 sourceVersion=source_version,
                                 notice=str((destination / 'copyright').relative_to(bundle)))
    # Debian copyright files refer to these absolute paths. Ship the texts too.
    shutil.copytree('/usr/share/common-licenses', bundle / 'licenses/debian-common', symlinks=False)
    for source, version in sorted({(p['source'], p['sourceVersion']) for p in packages.values()}):
        folder = sources / source
        folder.mkdir(exist_ok=True)
        subprocess.run(['apt-get', 'source', '--download-only', '--only-source', f'{source}={version}'],
                       cwd=folder, check=True)
        if not list(folder.glob('*.dsc')):
            raise RuntimeError('Source package descriptor missing: ' + source)
    inventory = {'packages': packages,
                 'files': {str(path): owners[origin] for path, origin in sorted(origins.items())},
                 'sourceFiles': {str(p.relative_to(bundle)): hashlib.sha256(p.read_bytes()).hexdigest()
                                 for p in sorted(sources.rglob('*')) if p.is_file()}}
    (bundle / 'licenses/NATIVE-PACKAGES.json').write_text(json.dumps(inventory, indent=2) + '\n')
    shutil.copy2(ROOT / 'LICENSING.md', bundle / 'LICENSING.md')
    return inventory


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    if args.write:
        (ROOT / 'licenses').mkdir(exist_ok=True)
        (ROOT / 'licenses/RUST-DEPENDENCIES.txt').write_text(rust_notices())
    else:
        check_rust_notices()
        print('Rust dependency notices match Cargo.lock and upstream license files.')
